-- Supabase storage for the stock workbench. Applied through ai-deploy to the user's schema.
-- MySQL Flyway migrations remain unchanged; do not run this file against MySQL.
CREATE TABLE stocks_instruments (
  owner_id UUID NOT NULL DEFAULT auth.uid(),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  market VARCHAR(12) NOT NULL, exchange_name VARCHAR(32) NOT NULL, code VARCHAR(24) NOT NULL,
  name VARCHAR(128) NOT NULL, page_url VARCHAR(512) NOT NULL, currency VARCHAR(8) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE, sort_order INTEGER NOT NULL DEFAULT 0,
  name_source VARCHAR(16) NOT NULL DEFAULT 'auto', created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL, name_updated_at BIGINT,
  PRIMARY KEY (owner_id,id), UNIQUE (owner_id,market,code)
);
ALTER TABLE stocks_instruments ENABLE ROW LEVEL SECURITY;
ALTER TABLE stocks_instruments FORCE ROW LEVEL SECURITY;
CREATE POLICY stocks_instruments_owner ON stocks_instruments FOR ALL USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

CREATE TABLE stocks_settings (
  owner_id UUID NOT NULL DEFAULT auth.uid(),
  setting_key VARCHAR(80) NOT NULL, setting_value TEXT NOT NULL,
  PRIMARY KEY (owner_id,setting_key)
);
ALTER TABLE stocks_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE stocks_settings FORCE ROW LEVEL SECURITY;
CREATE POLICY stocks_settings_owner ON stocks_settings FOR ALL USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

CREATE TABLE stocks_series (
  owner_id UUID NOT NULL DEFAULT auth.uid(),
  instrument_id BIGINT NOT NULL, period VARCHAR(12) NOT NULL,
  source TEXT NOT NULL, adjustment VARCHAR(128) NOT NULL, fetched_at BIGINT NOT NULL,
  previous_close DOUBLE PRECISION, note TEXT NOT NULL DEFAULT '',
  bars JSONB NOT NULL CHECK (jsonb_typeof(bars) = 'array'), revision UUID NOT NULL,
  PRIMARY KEY (owner_id,instrument_id,period), FOREIGN KEY (owner_id,instrument_id) REFERENCES stocks_instruments(owner_id,id) ON DELETE CASCADE,
  CHECK (period IN ('intraday','day','week','month','year'))
);
ALTER TABLE stocks_series ENABLE ROW LEVEL SECURITY;
ALTER TABLE stocks_series FORCE ROW LEVEL SECURITY;
CREATE POLICY stocks_series_owner ON stocks_series FOR ALL USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

